# Leading-commentary block detection. An output that begins with one of these
# phrases is treated as meta-commentary and stripped before any metric is
# computed; if nothing survives, the attempt is a pure-commentary failure
# (fmt = 0, regenerated by the gate when --agents).
#
# DELIBERATE DESIGN: only STRONG meta signals live here, and _clean_and_removed
# matches them against the FIRST ~150 chars of a block (preambles are short).
# Weak/ambiguous phrases that can appear inside real legal prose ("here is",
# "below is", "the following are", "the rules are", "please note") are NOT in
# this list: a false positive destroys a good rewrite, whereas a false negative
# merely keeps a preamble that r_fmt still penalises. Legal bullet glossaries
# (e.g. "**Simple explanations:**" + "- Term: ...") are legal content and kept.
CLEAN_BLOCK_RE = re.compile(
    r"(the user wants|this is a legal text rewriting task|i need to|i must|i will|"
    r"i should|i would|let me|the source text|the provided text|the input text|"
    r"reading difficulty|reading level|reading ease|previous attempt|the legal terms|"
    r"legal terms like|i have rewritten|this rewrite|my goal|my rewrite|"
    r"the target is|the goal is|i'm going to|i am going to|i plan to|i understand|"
    r"drafting plan|the instruction says|the following legal text|"
    r"here's my|here is my|below is my|^drafting|^analysis|^overview|"
    r"^summary|the source material|original text analysis)", re.I)


# Short leading "label" lines that preface a rewrite but are themselves
# meta-commentary (e.g. "Drafting:", "**Original Text Analysis:**").
LABEL_RE = re.compile(
    r"^\*{0,2}(drafting|analysis|overview|summary|notes?|comments?|rewritten"
    r"|simplified (version|text)|the rewrite|output|result|response)"
    r"\s*[:.\-]?\s*\*{0,2}\s*$", re.I)


def _is_planning_item(b):
    """A short bullet/numbered item (typical of a planning list) has few words
    and no internal multi-sentence punctuation. Long legal paragraphs survive."""
    return (len(b.split()) < 30
            and not re.search(r"[.!?]\s+[A-Z]", b))


def _clean_and_removed(rew):
    """Return (cleaned_text, removed_any). removed_any=True when substantive
    leading content (a label line, a meta-commentary block, or a planning item)
    was dropped from the start of rew -- NOT mere whitespace normalization
    (single newlines inside a block are preserved, as for legal bullet lists).
    """
    blocks = [b.strip() for b in re.split(r"\n\s*\n", rew) if b.strip()]
    kept, started, in_preamble, removed = [], False, False, False
    for b in blocks:
        if not started:
            # strip a single leading label line ("Drafting:", "**Analysis:**",
            # "The rewrite:") before deciding whether the rest is commentary.
            lines = b.split("\n")
            if len(lines) > 1 and LABEL_RE.match(lines[0].strip()):
                b = " ".join(lines[1:]).strip()
                if len(b.split()) < 8:
                    removed = True
                    continue      # label + short fragment -> still commentary
                removed = True
            is_meta = bool(CLEAN_BLOCK_RE.search(b[:150]))
            if is_meta:
                removed = True
                in_preamble = True
                continue
            if in_preamble and (b.startswith(("-", "*", "•"))
                                or re.match(r"^\d+[\.\)]", b)) \
                    and _is_planning_item(b):
                removed = True
                continue          # bulleted planning continuation
            started = True
        kept.append(b)
    out = " ".join(kept).strip()
    if len(out.split()) < 8:
        out = ""
        if blocks:
            removed = True        # too fragmentary to be a rewrite
    return out, removed


def clean_output(rew):
    """Strip any leading meta-commentary/planning block, returning only the
    actual rewrite. Returns '' if nothing legal-prose survived (pure commentary).
    """
    return _clean_and_removed(rew)[0]


def stripped_info(rew):
    """True iff clean_output drops substantive leading content from rew (as
    opposed to normalizing whitespace). Pure-commentary outputs -> True."""
    return _clean_and_removed(rew)[1]

