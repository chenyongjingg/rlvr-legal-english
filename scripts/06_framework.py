# ---------------- RAG: LegalGraphRAG-lite ----------------
class MiniLMEmbed:
    """Direct HF AutoModel embedding (sentence_transformers version mismatch)."""
    def __init__(self, model_dir, dev="cuda:0"):
        from transformers import AutoModel, AutoTokenizer
        self.tok = AutoTokenizer.from_pretrained(model_dir)
        self.model = AutoModel.from_pretrained(model_dir).to(dev).eval()
        self.dev = dev

    def encode(self, texts, normalize_embeddings=True, batch_size=32,
               show_progress_bar=False):
        outs = []
        for i in range(0, len(texts), batch_size):
            batch = texts[i:i + batch_size]
            enc = self.tok(batch, padding=True, truncation=True, max_length=256,
                           return_tensors="pt").to(self.dev)
            with torch.no_grad():
                out = self.model(**enc)
            mask = enc["attention_mask"].unsqueeze(-1)
            pooled = (out.last_hidden_state * mask).sum(1) / mask.sum(1)
            if normalize_embeddings:
                pooled = torch.nn.functional.normalize(pooled, dim=1)
            outs.append(pooled.cpu().numpy())
        return np.concatenate(outs, axis=0)


class RagIndex:
    def __init__(self, kb, emb_model, terms):
        self.kb = kb                      # list of {id, text} train+val only
        self.terms = terms                # list of term strings
        self.term_defs = {}
        self.emb_model = emb_model
        self.texts = [s["text"] for s in kb]
        self.ids = [s["id"] for s in kb]
        embs = emb_model.encode(self.texts, normalize_embeddings=True,
                                batch_size=32, show_progress_bar=False)
        import faiss
        self.index = faiss.IndexFlatIP(embs.shape[1])
        self.index.add(np.ascontiguousarray(embs.astype("float32")))
        self.doc_terms = [self._terms_in(t) for t in self.texts]
        self._load_defs()

    def _load_defs(self):
        c = json.load(open(os.path.join(DATA, "corpus_v2.json"), encoding="utf-8"))
        raw = c.get("terms", [])
        for t in raw:
            if isinstance(t, dict):
                self.term_defs[t.get("term", "")] = t.get("definition", "")
            else:
                self.term_defs[t] = ""

    def _terms_in(self, text):
        low = text.lower()
        return [t for t in self.terms if t.lower() in low]

    def retrieve(self, src, k=2):
        """dense + graph(shared-term) fusion, exclude source-like ids."""
        q = self.emb_model.encode([src], normalize_embeddings=True).astype("float32")
        scores, idx = self.index.search(q, min(8, len(self.texts)))
        cand = {}
        for s, i in zip(scores[0], idx[0]):
            sid = self.ids[i]
            if sid in src:            # don't retrieve the source itself
                continue
            cand[sid] = 0.7 * float(s) + 0.3 * 0.0
        # graph signal: snippets sharing terms with the source
        st = self._terms_in(src)
        if st:
            for i, doc_ts in enumerate(self.doc_terms):
                shared = len(set(st) & set(doc_ts))
                if shared and self.ids[i] not in src:
                    sid = self.ids[i]
                    cand[sid] = cand.get(sid, 0.0) + 0.4 * (shared / max(1, len(st)))
        top = sorted(cand.items(), key=lambda kv: -kv[1])[:k]
        return [self.kb[self.ids.index(sid)] for sid, _ in top]

    def term_context(self, src):
        st = self._terms_in(src)
        out = []
        for t in st[:6]:
            d = self.term_defs.get(t, "")
            out.append(f'- Term "{t}": {d}' if d else f'- Term "{t}"')
        return "\n".join(out)


def build_rag_ctx(rag, src):
    ctx = []
    tc = rag.term_context(src)
    if tc:
        ctx.append("Key legal terms used in this text:\n" + tc)
    passages = rag.retrieve(src)
    if passages:
        ctx.append("Related legal passages for context:")
        for p in passages:
            ctx.append("> " + p["text"][:280].replace("\n", " "))
    if ctx:
        return "The following legal knowledge is retrieved to assist generation:\n" + \
               "\n\n".join(ctx) + "\n\n"
    return ""


# ---------------- Agent 3/4: gate + corrective feedback ----------------
def gate_feedback(parts, fre, lv, src, terms, rew):
    """Return (pass, notes). pass=False triggers regeneration with notes."""
    notes = []
    if parts["faith"] < 0.35:
        notes.append("FIDELITY: your rewrite lost or changed legal facts; preserve every "
                     "legal rule from the source exactly, do not add or drop obligations.")
    if parts["diff"] < 0.40:   # |fre - target| > 12 points -> ask for another pass
        tgt = LEVEL_TARGET_FRE[lv]
        if fre > tgt:
            notes.append("DIFFICULTY: still too hard; use shorter sentences and simpler "
                         "everyday words.")
        else:
            notes.append("DIFFICULTY: still too easy/vague; keep more precise legal "
                         "wording and structure.")
    if parts["term"] < 0.5:
        present = [t for t in terms if t.lower() in src.lower()]
        kept = [t for t in present if t.lower() not in rew.lower()]
        if kept:
            notes.append("TERMS: keep these key legal terms verbatim: " + ", ".join(kept[:6]))
    if parts["fmt"] < 0.7:
        notes.append("FORMAT: output ONLY the rewrite text, no explanation or preamble.")
    return (len(notes) == 0, "; ".join(notes))


